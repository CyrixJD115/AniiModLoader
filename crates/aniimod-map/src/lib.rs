//! aniimod-map — the verified scrambled-export map.
//!
//! Aniimo's GameAssembly.dll renames every `il2cpp_*` export to an
//! `i0…` string (390 named exports, ordinals 25–269 in stock-API
//! alphabetical order, with a handful of FunPlus customs shifting local
//! windows — see `docs/findings.md`). This crate owns the mapping
//! `real name -> scrambled name` and its integrity gate.
//!
//! Responsibilities:
//! * parse `assets/Il2CppNameMap.txt` (`real=scrambled`, 238 entries)
//! * anchor-check a handful of twin/thunk-proven entries before use
//! * refuse to serve a map whose GameAssembly checksum doesn't match the
//!   one the map was generated for (SHA-512 prefix)
//!
//! Regeneration on game updates is offline tooling (`tools/exportmap`),
//! not part of the shipped engine.

#![forbid(unsafe_code)]

use std::collections::HashMap;

/// Baked, verified map. V3 (2026-09-28 update): the update rescrambled
/// every export name but left the code layout byte-identical, so the map
/// was regenerated by proven ordinal join (tools/exportmap/regen.py) —
/// every entry's wrapper body matched V2 byte-for-byte at the same
/// ordinal, and il2cpp_runtime_invoke's thunk target still carries the
/// body-verified prologue `48 89 5C 24 08 48 89 74 24 10 4C 89 4C 24 20 57`.
pub const BAKED_MAP: &str = include_str!("../../../assets/Il2CppNameMap.txt");

/// SHA-512 (hex, first 32 chars) of the GameAssembly.dll this map was
/// verified against. A mismatching game build must fail loudly.
pub const EXPECTED_GAME_ASSEMBLY_SHA512_PREFIX: &str = "f8311aa30acc59322dc790dcb55b212f";

#[derive(Debug)]
pub struct ExportMap {
    real_to_scrambled: HashMap<&'static str, &'static str>,
}

impl ExportMap {
    /// Load the baked map. Panics on parse failure — the file is compiled in.
    pub fn baked() -> Self {
        let mut real_to_scrambled = HashMap::new();
        for line in BAKED_MAP.lines() {
            let line = line.trim();
            if line.is_empty() {
                continue;
            }
            let (real, scrambled) = line
                .split_once('=')
                .expect("map lines are `real=scrambled`");
            real_to_scrambled.insert(real, scrambled);
        }
        Self { real_to_scrambled }
    }

    pub fn len(&self) -> usize {
        self.real_to_scrambled.len()
    }

    pub fn is_empty(&self) -> bool {
        self.real_to_scrambled.is_empty()
    }

    /// Resolve a real il2cpp API name to its scrambled export name.
    pub fn resolve(&self, real: &str) -> Option<&'static str> {
        self.real_to_scrambled.get(real).copied()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn baked_map_has_anchors() {
        let map = ExportMap::baked();
        assert_eq!(map.len(), 238);
        // twin/thunk/live-proven anchors (docs/findings.md); V3 values
        // re-proven by byte-identical ordinal join + runtime_invoke prologue
        assert_eq!(map.resolve("il2cpp_init"), Some("i0846a07r1p"));
        assert_eq!(map.resolve("il2cpp_domain_get"), Some("i04dbwei34ykoieut"));
        assert_eq!(
            map.resolve("il2cpp_domain_get_assemblies"),
            Some("i04em2d0zyv5t3vnq4fb71cuyhgl")
        );
        assert_eq!(
            map.resolve("il2cpp_assembly_get_image"),
            Some("i00bng3dklhbmosg1aov0z3vy")
        );
        // the mirrored pair that cost us a boot in V2 — both present, distinct
        assert_eq!(map.resolve("il2cpp_runtime_invoke"), Some("i0bbjvk14goirnh0npy16"));
        assert_eq!(
            map.resolve("il2cpp_runtime_invoke_convert_args"),
            Some("i0baqufc8ngaeiul0fgdk1p7y")
        );
    }
}
